HandleCursor_02_60F9:
LD A, [HL+]                                                 ;amount of options in a single block
LD C, A                                                     ;into C it goes

LD A, [HL+]                                                 ;
LD [$C622], A                                               ;not really used...

LD A, [HL+]                                                 ;
LD [CursorXPos], A                                          ;x-position, which is one and only in this game.

LDH A, [JoypadInputPress]                                   ;check if pressed up
BitTest JoypadInput_Up, A                                   ;
JR Z, CODE_02_611A                                          ;

LD A, SFX_CursorMove                                        ;
LDH [SFXQueue], A                                           ;cursor move SFX

CODE_02_610D:
LD A, B                                                     ;current option...
AND A                                                       ;if it's 0
JR NZ, CODE_02_6112                                         ;

LD B, C                                                     ;wrap-around

CODE_02_6112:
DEC B                                                       ;go back 1 option
CALL CheckDisabledOptions_02_614B                                           ;

JR C, CODE_02_610D                                          ;skip this option if beaten the level (land select)
JR CODE_02_6138

CODE_02_611A:
AND JoypadInput_Down|JoypadInput_Select                     ;check if pressed down or SELECT
JR Z, CODE_02_6130

LD A, SFX_CursorMove                                        ;
LDH [SFXQueue], A                                           ;cursor SFX

CODE_02_6122:
INC B                                                       ;go forward 1 option

LD A, B                                                     ;
CP C                                                        ;check if reached max
JR C, CODE_02_6129

LD B, $00                                                   ;wrap-around

CODE_02_6129:
CALL CheckDisabledOptions_02_614B
JR C, CODE_02_6122                                          ;skip option if can (in case of beaten land)
JR CODE_02_6138

CODE_02_6130:
LDH A, [JoypadInputPress]                                   ;
AND JoypadInput_A|JoypadInput_Start                         ;check if pressed start or A button
